"""Generate torn-paper edge masks as data-URI SVGs in a CSS file.

Usage: python3 tools/torn.py > concepts/01-cut-the-bill/torn.css
Change SEED to get a different tear.
"""
import math
import random
from urllib.parse import quote

SEED = 7


def noise1d(rng, n, octaves):
    """Sum of smoothed random walks: (amplitude, step) pairs."""
    out = [0.0] * n
    for amp, step in octaves:
        knots = [rng.uniform(-1, 1) for _ in range(n // step + 3)]
        for i in range(n):
            k, t = divmod(i, step)
            t = t / step
            t = t * t * (3 - 2 * t)
            out[i] += amp * (knots[k] * (1 - t) + knots[k + 1] * t)
    return out


def jagged(rng, n, amp):
    return [rng.uniform(-amp, amp) for _ in range(n)]


def vertical_edges(rng, w, h, x_top, x_bot, step=3):
    """Photo edge and paper (fibre) edge running top to bottom."""
    n = h // step + 1
    coarse = noise1d(rng, n, [(26, 60), (10, 18), (4, 6)])
    fine = jagged(rng, n, 2.2)
    fibre = noise1d(rng, n, [(7, 30), (4, 8)])
    fibre_fine = jagged(rng, n, 3.2)
    photo, paper = [], []
    for i in range(n):
        y = min(i * step, h)
        base = x_top + (x_bot - x_top) * (y / h)
        x = base + coarse[i] + fine[i]
        photo.append((x, y))
        paper.append((x + 9 + abs(fibre[i]) * 1.6 + fibre_fine[i], y))
    return photo, paper


def horizontal_edge(rng, w, y_left, y_right, amp=1.0, step=3):
    n = w // step + 1
    coarse = noise1d(rng, n, [(10 * amp, 70), (5 * amp, 20), (2 * amp, 6)])
    fine = jagged(rng, n, 1.6 * amp)
    pts = []
    for i in range(n):
        x = min(i * step, w)
        base = y_left + (y_right - y_left) * (x / w)
        pts.append((x, base + coarse[i] + fine[i]))
    return pts


def fmt(pts):
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)


def svg(w, h, body):
    s = (f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}' "
         f"preserveAspectRatio='none'>{body}</svg>")
    return "url(\"data:image/svg+xml," + quote(s, safe=" =:/',") + "\")"


def poly(pts, fill="#000"):
    return f"<polygon fill='{fill}' points='{fmt(pts)}'/>"


def main():
    rng = random.Random(SEED)
    out = ["/* Generated by tools/torn.py — do not edit by hand. */", ":root {"]

    # Desktop hero: photo on the left, bills on the right.
    W, H = 1440, 900
    photo, paper = vertical_edges(rng, W, H, 800, 690)
    out.append(f"  --tear-photo: {svg(W, H, poly([(0, 0)] + photo + [(0, H)]))};")
    out.append(f"  --tear-paper: {svg(W, H, poly([(0, 0)] + paper + [(0, H)]))};")

    # Mobile hero: photo on top, bills below.
    W, H = 400, 900
    edge = horizontal_edge(rng, W, 470, 430, amp=0.9)
    fibre = [(x, y + 7 + abs(math.sin(x / 23)) * 6 + rng.uniform(-2.5, 2.5)) for x, y in edge]
    out.append(f"  --tear-photo-m: {svg(W, H, poly([(0, 0), (W, 0)] + edge[::-1] ))};")
    out.append(f"  --tear-paper-m: {svg(W, H, poly([(0, 0), (W, 0)] + fibre[::-1]))};")

    # Strip masks: opaque below (top edge) or above (bottom edge) a tear line.
    W, H = 1440, 40
    edge = horizontal_edge(rng, W, 20, 18, amp=0.8)
    out.append(f"  --tear-top: {svg(W, H, poly(edge + [(W, H), (0, H)]))};")
    edge = horizontal_edge(rng, W, 20, 22, amp=0.8)
    out.append(f"  --tear-bottom: {svg(W, H, poly([(0, 0), (W, 0)] + edge[::-1]))};")

    # Section divider: torn paper sheet with a lighter fibre edge.
    W, H = 1440, 80
    edge = horizontal_edge(rng, W, 44, 30, amp=1.4)
    fibre = [(x, y - 5 - abs(math.sin(x / 41)) * 5 + rng.uniform(-2, 2)) for x, y in edge]
    body = (poly(fibre + [(W, H), (0, H)], "#FBF9F4") +
            poly(edge + [(W, H), (0, H)], "#ECE6DB"))
    out.append(f"  --tear-divider: {svg(W, H, body)};")

    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
