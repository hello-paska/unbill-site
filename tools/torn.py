"""Generate torn-paper edge masks as data-URI SVGs in a CSS file.

Usage: python3 tools/torn.py > concepts/01-cut-the-bill/torn.css
Change SEED to get a different tear.
"""
import random
from urllib.parse import quote

SEED = 7


def noise1d(rng, n, octaves):
    """Sum of smoothed random walks: (amplitude, step) pairs."""
    out = [0.0] * n
    for amp, step in octaves:
        knots = [rng.uniform(-1, 1) for _ in range(n // step + 3)]
        for i in range(n):
            k, t = divmod(i, step)
            t = t / step
            t = t * t * (3 - 2 * t)
            out[i] += amp * (knots[k] * (1 - t) + knots[k + 1] * t)
    return out


def jagged(rng, n, amp):
    return [rng.uniform(-amp, amp) for _ in range(n)]


def horizontal_edge(rng, w, y_left, y_right, amp=1.0, step=3):
    n = w // step + 1
    coarse = noise1d(rng, n, [(10 * amp, 70), (5 * amp, 20), (2 * amp, 6)])
    fine = jagged(rng, n, 1.6 * amp)
    pts = []
    for i in range(n):
        x = min(i * step, w)
        base = y_left + (y_right - y_left) * (x / w)
        pts.append((x, base + coarse[i] + fine[i]))
    return pts


def fmt(pts):
    return " ".join(f"{x:.1f},{y:.1f}" for x, y in pts)


def svg(w, h, body):
    s = (f"<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 {w} {h}' "
         f"preserveAspectRatio='none'>{body}</svg>")
    return "url(\"data:image/svg+xml," + quote(s, safe=" =:/',") + "\")"


def poly(pts, fill="#000"):
    return f"<polygon fill='{fill}' points='{fmt(pts)}'/>"


def main():
    rng = random.Random(SEED)
    out = ["/* Generated by tools/torn.py — do not edit by hand. */", ":root {"]

    # Strip masks: opaque below (top edge) or above (bottom edge) a tear line.
    W, H = 1440, 40
    edge = horizontal_edge(rng, W, 20, 18, amp=0.8)
    out.append(f"  --tear-top: {svg(W, H, poly(edge + [(W, H), (0, H)]))};")
    edge = horizontal_edge(rng, W, 20, 22, amp=0.8)
    out.append(f"  --tear-bottom: {svg(W, H, poly([(0, 0), (W, 0)] + edge[::-1]))};")

    # Sheet tears: a paper edge plus a rougher white fibre edge just above it,
    # sized for sheets a few hundred pixels wide. Two variants for variety.
    W, H = 600, 40
    for n in (1, 2):
        edge = horizontal_edge(rng, W, 24, 22, amp=0.75, step=2)
        fibre = [(x, y - 3.5 - abs(rng.gauss(0, 2.2))) for x, y in edge]
        out.append(f"  --sheet-tear-{n}: {svg(W, H, poly(edge + [(W, H), (0, H)]))};")
        out.append(f"  --sheet-fibre-{n}: {svg(W, H, poly(fibre + [(W, H), (0, H)]))};")

    out.append("}")
    print("\n".join(out))


if __name__ == "__main__":
    main()
